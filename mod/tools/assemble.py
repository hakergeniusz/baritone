#!/usr/bin/env python3
"""Assemble the mod's brain into mixins/baritone/runtime.rs.

The game's mixin machinery takes one self-contained payload per module, so
the port's separate sources are flattened into a single file: each source
becomes a child module of the runtime, and `crate::` paths become `super::`
paths. Inside the game the runtime lands as `pub(crate) mod baritone` in
the client's game.rs; as the Cargo library the same file is the crate root,
where the same relative paths resolve to the same modules. The readable
sources stay here in `src/` (and the port's own `src/`); this file is
generated — don't edit it by hand.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PORT = ROOT.parent  # the repo root: the ported planner's crate

# Payload order matters: `brain_log` is defined before the modules that use
# it, and the tests' `super::super` walks reach only these siblings.
MODULES = [
    ("goals", PORT / "src" / "goals.rs"),
    ("movement", PORT / "src" / "pathing" / "movement.rs"),
    ("search", PORT / "src" / "pathing" / "search.rs"),
    ("world_view", ROOT / "src" / "world_view.rs"),
    ("bot", ROOT / "src" / "bot.rs"),
]

# The standalone port's module tree differs from the flat payload's:
# `crate::pathing::movement` becomes the payload's `super::movement`, and
# so on. The planner's `log::` calls compile as no-ops (see brain_log).
REWRITES = [
    ("crate::pathing::movement::", "super::movement::"),
    ("crate::pathing::search::", "super::search::"),
    ("crate::goals::", "super::goals::"),
    ("crate::world::", "super::world_view::"),
    ("log::warn!", "brain_log!"),
    ("log::debug!", "brain_log!"),
    ("log::info!", "brain_log!"),
    ("log::error!", "brain_log!"),
]

HEADER = """\
// Horizon Baritone: a pathfinding bot, ported from the Baritone mod
// (https://github.com/cabaletta/baritone, LGPL-3.0). Chat commands set a
// goal; each tick the bot plans a walkable path to it and drives the
// player along it with injected inputs — forward, sprint, step-up and
// parkour jumps — re-planning from wherever the player actually is when
// the path stops matching the world.
//
// This file is generated by tools/assemble.py from src/ (the planner,
// ported module by module) and mod/src/ (the game-facing brain): the
// sources become child modules, and `crate::` paths become `super::`
// paths, so the same file is both the bundle's payload (inside the game's
// game.rs, as `crate::game::baritone`) and this repo's test library.
//
// The brain is pure Rust: game access lives in the bundle's helper files,
// which hand in the player and a block reader and apply the returned
// inputs. Unloaded chunks read as air — passable but not walkable — so
// paths reach only as far as the loaded world and re-plan as it streams.

// The planner keeps its `log::` calls from the port (they document what a
// search is doing); inside the game they go nowhere — the payload must
// stay free of game and logging types — so they compile as no-ops.
macro_rules! brain_log {
    ($($arg:tt)*) => {{}};
}

"""


def main() -> None:
    parts = [HEADER]
    for name, path in MODULES:
        text = path.read_text()
        for old, new in REWRITES:
            text = text.replace(old, new)
        for marker in ("crate::", "log::"):
            if marker in text:
                raise SystemExit(f"{path}: unresolved `{marker}` path remains")
        parts.append(f"pub mod {name} {{\n{text}}}\n")
    out = ROOT / "mixins" / "baritone" / "runtime.rs"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(parts))
    print(f"assembled {out.relative_to(ROOT)} ({sum(1 for _ in out.open())} lines)")


if __name__ == "__main__":
    main()
